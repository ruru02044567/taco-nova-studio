# -*- coding: utf-8 -*-
"""D20S1 黑白史萊姆（對標 Felinemeow Ai 4,927 萬那支）音效配方。

⚠️ 本支刻意「不做混音」，這是對標實測後的裁示，不是偷懶。

2026-08-30 實測四支對標片的整體響度：
    HcF4AghIfKs（4,927 萬）  -33.0 LUFS   LRA 16.0
    aAPFQanOAhg（2,447 萬）  -24.9 LUFS
    uMYnI2au3hQ（2,083 萬）  -26.4 LUFS
    wld62Ek4pKc（  600 萬）  -23.8 LUFS
對照我們現行文法（d6s2 有聲版）：**-15.5 LUFS、LRA 3.4**。
→ 我們比對標大 10~17 dB、動態範圍只有它的五分之一。
   「BGM 鋪滿＋壓低再爆」那套文法是對標的反方向。

而 H3 生成時自帶原生音軌，實測落在 -28.7 ~ -21.9 LUFS，**正好在對標區間內**。
賢賢 8/29 也講過「音樂就是用它原聲的就好了」。

所以本支配方 = 保留 H3 原聲的「內容」，只修「音量」。

⚠️ 2026-08-30 實跑後修正：原本寫「什麼都不做」是錯的。
H3 這批生出來的原聲實測 **-54.5 LUFS、峰值 -27 dB、開頭 1.26 秒全靜音** ——
聲音有生出來，但小到人耳聽不見。這正是 8/29 賢賢說「沒有聲音阿」的同一件事。
昨天能聽的那幾支檔名都有「放大」二字，對照證實：修法是放大，不是重生、不是鋪 BGM。

作法：loudnorm=I=-24:TP=-1.5:LRA=11（單次，不做二次壓縮）
實測 d20a：-54.5 → -26.5 LUFS，峰值 -2.3 dB，靜音段 0，
每秒 RMS 有起伏（-43.4→-38.8→-42.7）代表放大的是內容不是底噪。

驗收基準（對照對標，程式量得到的部分）：
  - 整體響度落在 -33 ~ -21 LUFS      （超出＝不合格）
  - 無 0.3 秒以上的靜音段（-50dB 門檻）
  - 音軌存在且非全靜音（preflight 硬閘門會擋）
  - 好不好聽 → 賢賢裁決，我判不了

用法：python mix_d20s1.py <影片> <輸出>
"""
import subprocess
import sys

# 對標實測區間 -33 ~ -23.8 LUFS；取 -24 是為了不低於區間又不過亮。
LOUDNORM = 'loudnorm=I=-24:TP=-1.5:LRA=11'

if __name__ == '__main__':
    src, dst = sys.argv[1], sys.argv[2]
    r = subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src,
                        '-c:v', 'copy', '-af', LOUDNORM,
                        '-c:a', 'aac', '-b:a', '192k', dst])
    if r.returncode != 0:
        sys.exit('[d20s1] loudnorm 失敗')
    print('[d20s1] H3 原聲已放大到對標區間（%s）' % LOUDNORM)
